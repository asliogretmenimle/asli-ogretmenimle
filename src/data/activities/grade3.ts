/** Nokta grafiği: her nokta bir veriyi gösterir */
function dotPlot(labels: string[], counts: number[], caption: string): Visual {
  const gap = 60
  const w = 80 + (labels.length - 1) * gap
  const h = Math.max(...counts) * 20 + 80
  const base = h - 56
  const ticks = labels
    .map((l, i) => `<line x1="${40 + i * gap}" y1="${base - 5}" x2="${40 + i * gap}" y2="${base + 5}" stroke="${INK}" stroke-width="2"/><text x="${40 + i * gap}" y="${base + 24}" text-anchor="middle" font-size="14" font-weight="700" fill="${INK}">${l}</text>`)
    .join('')
  const dots = counts
    .flatMap((c, i) => Array.from({ length: c }, (_, k) => `<circle cx="${40 + i * gap}" cy="${base - 14 - k * 20}" r="8" fill="#6366f1"/>`))
    .join('')
  return { kind: 'svg', svg: `<svg viewBox="0 0 ${w} ${h}"><line x1="10" y1="${base}" x2="${w - 10}" y2="${base}" stroke="${INK}" stroke-width="2.5"/>${ticks}${dots}<text x="${w / 2}" y="${base + 46}" text-anchor="middle" font-size="13" font-weight="800" fill="${INK}">${caption}</text></svg>` }
}

