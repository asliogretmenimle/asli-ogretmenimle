/** Cetvel üzerinde kalem: start ile end (cm) arasında. Ölçmenin 0’dan başlamak zorunda olmadığını göstermek için */
function ruler(start: number, end: number): Visual {
  const x = (v: number) => 16 + v * 30
  const ticks = Array.from({ length: 11 }, (_, i) => `<line x1="${x(i)}" y1="46" x2="${x(i)}" y2="${i % 5 === 0 ? 62 : 58}" stroke="${INK}" stroke-width="2"/><text x="${x(i)}" y="78" text-anchor="middle" font-size="12" font-weight="700" fill="${INK}">${i}</text>`).join('')
  const halves = Array.from({ length: 10 }, (_, i) => `<line x1="${x(i + 0.5)}" y1="46" x2="${x(i + 0.5)}" y2="51" stroke="${INK}" stroke-width="1"/>`).join('')
  const pencil = `<rect x="${x(start)}" y="14" width="${x(end) - x(start) - 12}" height="18" rx="3" fill="#fbbf24" stroke="${INK}" stroke-width="2"/><polygon points="${x(end) - 12},14 ${x(end)},23 ${x(end) - 12},32" fill="#fde68a" stroke="${INK}" stroke-width="2"/>`
  const guides = `<line x1="${x(start)}" y1="8" x2="${x(start)}" y2="46" stroke="${RED}" stroke-width="1.5" stroke-dasharray="3 3"/><line x1="${x(end)}" y1="8" x2="${x(end)}" y2="46" stroke="${RED}" stroke-width="1.5" stroke-dasharray="3 3"/>`
  return { kind: 'svg', svg: `<svg viewBox="0 0 332 90"><rect x="4" y="44" width="324" height="42" rx="4" fill="#fef3c7" stroke="${INK}" stroke-width="2"/>${ticks}${halves}${pencil}${guides}</svg>` }
}

/** Litre çizgili ölçü kabı (level: litre, 0,5’in katları) */
function jug(level: number, max = 2): Visual {
  const top = 20, bottom = 150, h = bottom - top
  const y = (v: number) => bottom - (v / max) * h
  const label = (v: number) => (v === 0.5 ? '½ L' : Number.isInteger(v) ? `${v} L` : `${Math.floor(v)}½ L`)
  const marks = Array.from({ length: max * 2 }, (_, i) => (i + 1) / 2)
    .map((v) => `<line x1="76" y1="${y(v)}" x2="92" y2="${y(v)}" stroke="${INK}" stroke-width="2"/><text x="98" y="${y(v) + 5}" font-size="13" font-weight="800" fill="${INK}">${label(v)}</text>`)
    .join('')
  const water = level > 0 ? `<rect x="32" y="${y(level)}" width="58" height="${bottom - 2 - y(level)}" fill="#7dd3fc"/>` : ''
  return { kind: 'svg', svg: `<svg viewBox="0 0 150 160"><path d="M30 ${top} V${bottom} H92 V${top}" fill="#f8fafc" stroke="${INK}" stroke-width="3"/>${water}<path d="M30 ${top} V${bottom} H92 V${top}" fill="none" stroke="${INK}" stroke-width="3"/><path d="M30 45 C8 45 8 105 30 105" fill="none" stroke="${INK}" stroke-width="4"/>${marks}</svg>` }
}

/** Kibrit çöpüyle yan yana kareler: 1, 2, 3 kare (büyüyen örüntü) */
function matchSquares(stages: number[]): Visual {
  const s = 30
  let off = 10
  const sticks: string[] = []
  const stick = (x1: number, y1: number, x2: number, y2: number) => `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="#b45309" stroke-width="5" stroke-linecap="round"/>`
  for (const n of stages) {
    for (let i = 0; i < n; i++) {
      const x = off + i * s
      sticks.push(stick(x + 3, 12, x + s - 3, 12), stick(x + 3, 12 + s, x + s - 3, 12 + s), stick(x + s, 15, x + s, 9 + s))
      if (i === 0) sticks.push(stick(x, 15, x, 9 + s))
    }
    off += n * s + 26
  }
  return { kind: 'svg', svg: `<svg viewBox="0 0 ${off} ${s + 26}">${sticks.join('')}</svg>` }
}

